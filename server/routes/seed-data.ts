// Demo dataset for the Delivery Console, ported from the
// approved claude.ai/design prototype ("Engagement Execution Console.dc.html").

export interface SeedTicket {
  key: string;
  title: string;
  status: string;
  assignee: string;
  est: string;
  workstream: string;
  agent: boolean;
  sources: { type: string; label: string }[];
  description: string;
  ac: string[];
  blocked: boolean;
}

const DEFAULT_DESC =
  'Migrate and validate the workload described in the linked source. Scope confirmed with client on the last working session.';
const DEFAULT_AC = [
  'Output parity validated against legacy system',
  'Runbook updated in SharePoint',
  'Client sign-off recorded',
];

function T(
  key: string,
  title: string,
  status: string,
  assignee: string,
  est: string,
  workstream: string,
  agent: boolean,
  sources: { type: string; label: string }[],
  description?: string,
  ac?: string[],
  blocked?: boolean,
): SeedTicket {
  return {
    key,
    title,
    status,
    assignee,
    est,
    workstream,
    agent,
    sources,
    description: description ?? DEFAULT_DESC,
    ac: ac ?? DEFAULT_AC,
    blocked: !!blocked,
  };
}

